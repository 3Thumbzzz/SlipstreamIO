"""Waveform peak extraction.

Test audio is generated by ffmpeg itself, so the suite needs no binary fixture.
"""

import os
import subprocess
import sys

import numpy as np
import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from trackcleaner.audio import peaks as pk                        # noqa: E402


def _have_ffmpeg() -> bool:
    try:
        subprocess.run(["ffmpeg", "-version"], capture_output=True, timeout=15)
        return True
    except (OSError, subprocess.TimeoutExpired):
        return False


needs_ffmpeg = pytest.mark.skipif(not _have_ffmpeg(), reason="ffmpeg not on PATH")


def _make_tone(path, duration=3, gain=8):
    """ffmpeg's sine generator runs at about -18 dBFS, so push it up to make
    amplitude assertions meaningful."""
    subprocess.run(
        ["ffmpeg", "-v", "quiet", "-y", "-f", "lavfi",
         "-i", f"sine=frequency=440:duration={duration}",
         "-af", f"volume={gain}", path],
        capture_output=True, timeout=60,
    )
    return path


@pytest.fixture(scope="module")
def tone(tmp_path_factory):
    """A 3-second 440 Hz tone as a real MP3, near full scale."""
    return _make_tone(str(tmp_path_factory.mktemp("audio") / "tone.mp3"))


@needs_ffmpeg
def test_envelope_has_fixed_width_and_sane_range(tone):
    pk.cache_clear()
    p = pk.load_peaks(tone)
    assert p is not None
    assert len(p.lo) == len(p.hi) == pk.COLUMNS
    assert p.lo.min() >= -1.0 and p.hi.max() <= 1.0
    assert (p.hi >= p.lo).all(), "max must never fall below min"
    assert p.hi.max() > 0.5, "a loud tone must show real amplitude"
    assert p.duration == pytest.approx(3.0, abs=0.15)


@needs_ffmpeg
def test_envelope_amplitude_tracks_the_signal(tmp_path):
    """The envelope must reflect how loud the audio actually is -- the property
    that makes the waveform meaningful rather than decorative."""
    pk.cache_clear()
    loud = pk.load_peaks(_make_tone(str(tmp_path / "loud.mp3"), gain=8))
    quiet = pk.load_peaks(_make_tone(str(tmp_path / "quiet.mp3"), gain=1))
    assert loud.hi.max() > quiet.hi.max() * 3


@needs_ffmpeg
def test_silence_yields_a_flat_envelope(tmp_path):
    path = str(tmp_path / "silence.mp3")
    subprocess.run(
        ["ffmpeg", "-v", "quiet", "-y", "-f", "lavfi",
         "-i", "anullsrc=r=44100:cl=mono", "-t", "1", path],
        capture_output=True, timeout=60,
    )
    pk.cache_clear()
    p = pk.load_peaks(path)
    assert p is not None
    assert np.abs(p.hi).max() < 0.01 and np.abs(p.lo).max() < 0.01


@needs_ffmpeg
def test_second_call_is_served_from_cache(tone):
    pk.cache_clear()
    first = pk.load_peaks(tone)
    assert pk.load_peaks(tone) is first, "same object -> no re-decode"


@needs_ffmpeg
def test_touching_the_file_invalidates_the_cache(tone, tmp_path):
    pk.cache_clear()
    copy = str(tmp_path / "copy.mp3")
    with open(tone, "rb") as src, open(copy, "wb") as dst:
        dst.write(src.read())
    first = pk.load_peaks(copy)
    os.utime(copy, (0, 0))                       # pretend it was edited
    assert pk.load_peaks(copy) is not first


@needs_ffmpeg
def test_binning_down_preserves_the_envelope(tone):
    pk.cache_clear()
    p = pk.load_peaks(tone)
    lo, hi = p.binned(500)
    assert len(lo) == len(hi) == 500
    assert (hi >= lo).all()
    # re-binning must not invent amplitude beyond the original
    assert hi.max() <= p.hi.max() + 1e-6
    assert lo.min() >= p.lo.min() - 1e-6


@needs_ffmpeg
def test_binning_up_is_a_no_op(tone):
    pk.cache_clear()
    p = pk.load_peaks(tone)
    lo, hi = p.binned(pk.COLUMNS * 4)
    assert len(lo) == pk.COLUMNS


def test_missing_file_returns_none_rather_than_raising(tmp_path):
    assert pk.load_peaks(str(tmp_path / "nope.mp3")) is None


def test_undecodable_file_returns_none(tmp_path):
    junk = tmp_path / "junk.mp3"
    junk.write_bytes(b"this is definitely not audio" * 50)
    assert pk.load_peaks(str(junk)) is None


@needs_ffmpeg
def test_very_short_file_still_yields_a_full_width_envelope(tmp_path):
    """A file shorter than COLUMNS samples must not produce a ragged array."""
    path = str(tmp_path / "blip.mp3")
    subprocess.run(
        ["ffmpeg", "-v", "quiet", "-y", "-f", "lavfi",
         "-i", "sine=frequency=440:duration=0.05", path],
        capture_output=True, timeout=60,
    )
    pk.cache_clear()
    p = pk.load_peaks(path)
    assert p is not None
    assert len(p.lo) == len(p.hi) == pk.COLUMNS
    assert np.isfinite(p.lo).all() and np.isfinite(p.hi).all()


